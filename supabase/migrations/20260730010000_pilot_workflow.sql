-- Congela o contexto analítico dos resultados legados. Novas versões são criadas
-- pela API com a mesma estrutura e nunca dependem do cadastro mutável no laudo.
update public.resultado_analise ra
set snapshot_analitico = (
  select jsonb_build_object(
    'schema_version', 1,
    'versao_resultado', coalesce(ra.versao, 1),
    'valor_medido', ra.valor_medido,
    'valor_qualitativo', ra.valor_qualitativo,
    'datacoleta', ra.datacoleta,
    'parametro', jsonb_build_object(
      'id', p.id,
      'nome', p.nome,
      'unidade_medida', p.unidade_medida,
      'tipo_resultado', p.tipo_resultado,
      'categoria', p.categoria
    ),
    'matriz', jsonb_build_object('id', m.id, 'nome', m.nome),
    'referencia_legal', jsonb_build_object(
      'legislacao_id', l.id,
      'legislacao_nome', l.nome,
      'legislacao_sigla', l.sigla,
      'contexto_id', lc.id,
      'contexto_codigo', lc.codigo,
      'contexto_nome', lc.nome,
      'limite_minimo', coalesce(ra.limite_minimo_aplicado, p.limite_minimo),
      'limite_maximo', coalesce(ra.limite_maximo_aplicado, p.limite_maximo),
      'tipo_limite', coalesce(ra.tipo_limite_aplicado, p.tipo_limite),
      'criterio', coalesce(ra.criterio_legal_aplicado, p.criterio_texto),
      'fonte', coalesce(ra.fonte_legal_aplicada, p.fonte_referencia)
    ),
    'metodo', case when ma.id is null then null else jsonb_build_object(
      'id', ma.id,
      'codigo', ma.codigo,
      'nome', ma.nome,
      'versao', ma.versao,
      'referencia_normativa', ma.referencia_normativa,
      'unidade_resultado', ma.unidade_resultado,
      'limite_deteccao', ma.limite_deteccao,
      'limite_quantificacao', ma.limite_quantificacao,
      'incerteza_padrao', ma.incerteza_padrao
    ) end,
    'legado_sem_assinatura', true,
    'publicacao_legada_em', ra.datadapublicacao
  )
  from public.parametro p
  join public.amostra a on a.id = ra.amostra_id
  join public.matriz m on m.id = a.matriz_id
  join public.legislacao l on l.id = p.legislacao_id
  join public.legislacao_contexto lc on lc.id = p.contexto_legislacao_id
  left join public.metodo_analitico ma on ma.id = ra.metodo_analitico_id
  where p.id = ra.parametro_id
)
where ra.snapshot_analitico is null;

