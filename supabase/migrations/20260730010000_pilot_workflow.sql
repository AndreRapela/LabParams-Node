create or replace function public.bind_assinatura_context()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  current_version integer;
  current_status text;
  expected_destination text;
  metadata_version integer;
begin
  if new.authenticated_at > new.signed_at
     or new.signed_at > new.authenticated_at + interval '5 minutes' then
    raise exception 'Janela temporal da assinatura eletronica invalida';
  end if;

  if new.signed_at < clock_timestamp() - interval '5 minutes'
     or new.signed_at > clock_timestamp() + interval '30 seconds' then
    raise exception 'Assinatura eletronica expirada ou com data futura';
  end if;

  if new.entity_type = 'resultado_analise'
     and new.action in ('APPROVE', 'REJECT', 'PUBLISH', 'REOPEN') then
    if new.entity_id !~ '^[1-9][0-9]*$' or length(new.entity_id) > 10 then
      raise exception 'Identificador de resultado invalido na assinatura eletronica';
    end if;

    select result.versao, result.status_resultado
      into current_version, current_status
    from public.resultado_analise result
    where result.id = new.entity_id::bigint
      and result.deleted_at is null;

    if not found then
      raise exception 'Resultado da assinatura eletronica nao encontrado';
    end if;

    expected_destination := case
      when new.action = 'APPROVE' and current_status = 'em_revisao' then 'aprovado'
      when new.action = 'REJECT' and current_status = 'em_revisao' then 'rejeitado'
      when new.action = 'PUBLISH' and current_status = 'aprovado' then 'publicado'
      when new.action = 'REOPEN' and current_status = 'aprovado' then 'rascunho'
      else null
    end;

    if expected_destination is null then
      raise exception 'Acao de assinatura incompativel com o estado atual do resultado';
    end if;

    if coalesce(new.metadata ->> 'entity_version', '') !~ '^[1-9][0-9]*$' then
      raise exception 'Versao do resultado ausente na assinatura eletronica';
    end if;
    metadata_version := (new.metadata ->> 'entity_version')::integer;

    if metadata_version <> current_version
       or new.metadata ->> 'status_origin' is distinct from current_status
       or new.metadata ->> 'status_destination' is distinct from expected_destination then
      raise exception 'Contexto da assinatura nao corresponde a transicao do resultado';
    end if;

    if new.entity_version is not null and new.entity_version <> current_version then
      raise exception 'Versao estrutural da assinatura diverge do resultado';
    end if;
    if new.status_origem is not null and new.status_origem is distinct from current_status then
      raise exception 'Estado de origem estrutural da assinatura diverge do resultado';
    end if;
    if new.status_destino is not null and new.status_destino is distinct from expected_destination then
      raise exception 'Estado de destino estrutural da assinatura diverge do resultado';
    end if;

    new.entity_version := current_version;
    new.status_origem := current_status;
    new.status_destino := expected_destination;
  end if;

  return new;
end;
$$;

create or replace function public.protect_resultado_workflow_content()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  required_action text;
  required_actor uuid;
  matching_signature_id bigint;
  matching_signature_count integer;
begin
  if tg_op = 'DELETE' then
    if old.status_resultado in ('em_revisao', 'aprovado', 'publicado') then
      raise exception 'Resultado em revisão, aprovado ou publicado não pode ser removido';
    end if;
    return old;
  end if;

  if old.status_resultado = 'publicado' then
    raise exception 'Resultado publicado é imutável';
  end if;

  if old.status_resultado is distinct from new.status_resultado and not (
    (old.status_resultado = 'rascunho' and new.status_resultado = 'em_revisao')
    or (old.status_resultado = 'em_revisao' and new.status_resultado in ('aprovado', 'rejeitado'))
    or (old.status_resultado = 'rejeitado' and new.status_resultado = 'rascunho')
    or (old.status_resultado = 'aprovado' and new.status_resultado in ('rascunho', 'publicado'))
  ) then
    raise exception 'Transição inválida do workflow de resultado: % para %',
      old.status_resultado, new.status_resultado;
  end if;

  required_action := case
    when old.status_resultado = 'em_revisao' and new.status_resultado = 'aprovado'
      then 'APPROVE'
    when old.status_resultado = 'em_revisao' and new.status_resultado = 'rejeitado'
      then 'REJECT'
    when old.status_resultado = 'aprovado' and new.status_resultado = 'publicado'
      then 'PUBLISH'
    when old.status_resultado = 'aprovado' and new.status_resultado = 'rascunho'
      then 'REOPEN'
    else null
  end;

  required_actor := case required_action
    when 'APPROVE' then new.aprovado_por
    when 'REJECT' then new.rejeitado_por
    when 'PUBLISH' then new.publicado_por
    else null
  end;

  if required_action is not null then
    select count(*)::integer, min(signature.id)
      into matching_signature_count, matching_signature_id
    from public.assinatura_eletronica signature
    where signature.entity_type = 'resultado_analise'
      and signature.entity_id = new.id::text
      and signature.action = required_action
      and (required_actor is null or signature.signer_user_id = required_actor)
      and signature.entity_version = old.versao
      and signature.entity_version = new.versao
      and signature.status_origem = old.status_resultado
      and signature.status_destino = new.status_resultado
      and signature.authenticated_at <= signature.signed_at
      and signature.signed_at <= signature.authenticated_at + interval '5 minutes'
      and signature.signed_at >= clock_timestamp() - interval '5 minutes'
      and signature.signed_at <= clock_timestamp() + interval '30 seconds'
      and signature.id is distinct from old.ultima_assinatura_eletronica_id
      and not exists (
        select 1
        from public.resultado_workflow_evento used_event
        where used_event.assinatura_eletronica_id = signature.id
      );

    if matching_signature_count <> 1 then
      raise exception 'A transicao exige exatamente uma assinatura nova e ainda nao utilizada';
    end if;

    if new.ultima_assinatura_eletronica_id is not null
       and new.ultima_assinatura_eletronica_id <> matching_signature_id then
      raise exception 'A assinatura indicada nao corresponde a transicao do resultado';
    end if;
    new.ultima_assinatura_eletronica_id := matching_signature_id;
  elsif new.ultima_assinatura_eletronica_id is distinct from old.ultima_assinatura_eletronica_id then
    raise exception 'A ultima assinatura so pode mudar em uma transicao assinada';
  end if;

  if new.status_resultado = 'em_revisao'
     and old.status_resultado is distinct from new.status_resultado
     and (
       new.metodo_analitico_id is null
       or jsonb_typeof(new.snapshot_analitico -> 'metodo') is distinct from 'object'
     ) then
    raise exception 'Método e snapshot analítico são obrigatórios para revisão';
  end if;

  if new.status_resultado = 'aprovado'
     and old.status_resultado is distinct from new.status_resultado then
    if new.aprovado_por is null or new.aprovado_por = old.submetido_por then
      raise exception 'Aprovação exige revisor diferente do responsável pela submissão';
    end if;
  end if;

  if new.status_resultado = 'rejeitado'
     and old.status_resultado is distinct from new.status_resultado then
    if new.rejeitado_por is null or new.rejeitado_por = old.submetido_por then
      raise exception 'Rejeição exige revisor diferente do responsável pela submissão';
    end if;
  end if;

  if old.status_resultado in ('em_revisao', 'aprovado') and (
    old.valor_medido is distinct from new.valor_medido
    or old.valor_qualitativo is distinct from new.valor_qualitativo
    or old.amostra_id is distinct from new.amostra_id
    or old.parametro_id is distinct from new.parametro_id
    or old.contexto_legislacao_id is distinct from new.contexto_legislacao_id
    or old.datacoleta is distinct from new.datacoleta
    or old.metodo_analitico_id is distinct from new.metodo_analitico_id
    or old.snapshot_analitico is distinct from new.snapshot_analitico
    or old.versao is distinct from new.versao
    or old.limite_minimo_aplicado is distinct from new.limite_minimo_aplicado
    or old.limite_maximo_aplicado is distinct from new.limite_maximo_aplicado
    or old.tipo_limite_aplicado is distinct from new.tipo_limite_aplicado
    or old.criterio_legal_aplicado is distinct from new.criterio_legal_aplicado
    or old.fonte_legal_aplicada is distinct from new.fonte_legal_aplicada
  ) then
    raise exception 'Conteúdo analítico bloqueado durante revisão ou após aprovação';
  end if;
  return new;
end;
$$;

create or replace function public.enforce_resultado_workflow_event_signature()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  current_version integer;
  current_status text;
  current_signature_id bigint;
  required_action text;
  required_decision text;
  signature_record public.assinatura_eletronica%rowtype;
begin
  select result.versao, result.status_resultado,
         result.ultima_assinatura_eletronica_id
    into current_version, current_status, current_signature_id
  from public.resultado_analise result
  where result.id = new.resultado_id;

  if not found then
    raise exception 'Resultado do evento de workflow nao encontrado';
  end if;

  if current_status is distinct from new.status_novo then
    raise exception 'Evento de workflow nao corresponde ao estado atual do resultado';
  end if;

  if new.resultado_versao is not null and new.resultado_versao <> current_version then
    raise exception 'Versao do evento diverge da versao atual do resultado';
  end if;
  new.resultado_versao := current_version;

  required_action := case
    when new.status_anterior = 'em_revisao' and new.status_novo = 'aprovado'
      then 'APPROVE'
    when new.status_anterior = 'em_revisao' and new.status_novo = 'rejeitado'
      then 'REJECT'
    when new.status_anterior = 'aprovado' and new.status_novo = 'publicado'
      then 'PUBLISH'
    when new.status_anterior = 'aprovado' and new.status_novo = 'rascunho'
      then 'REOPEN'
    else null
  end;

  required_decision := case required_action
    when 'APPROVE' then 'aprovacao'
    when 'REJECT' then 'rejeicao'
    when 'PUBLISH' then 'publicacao'
    when 'REOPEN' then 'reabertura'
    else null
  end;

  if required_action is null then
    if new.assinatura_eletronica_id is not null then
      raise exception 'Assinatura nao permitida para este evento de workflow';
    end if;
    return new;
  end if;

  if new.decisao is distinct from required_decision then
    raise exception 'Decisao do evento nao corresponde a transicao assinada';
  end if;
  if new.actor_user_id is null then
    raise exception 'Ator e obrigatorio em evento de transicao assinada';
  end if;
  if new.assinatura_eletronica_id is null
     or new.assinatura_eletronica_id is distinct from current_signature_id then
    raise exception 'Evento nao referencia a ultima assinatura do resultado';
  end if;

  select signature.* into signature_record
  from public.assinatura_eletronica signature
  where signature.id = new.assinatura_eletronica_id;

  if not found
     or signature_record.entity_type is distinct from 'resultado_analise'
     or signature_record.entity_id is distinct from new.resultado_id::text
     or signature_record.signer_user_id is distinct from new.actor_user_id
     or signature_record.action is distinct from required_action
     or signature_record.entity_version is distinct from current_version
     or signature_record.status_origem is distinct from new.status_anterior
     or signature_record.status_destino is distinct from new.status_novo then
    raise exception 'Assinatura nao corresponde a entidade, ator, acao, versao e estados do evento';
  end if;

  if signature_record.authenticated_at > signature_record.signed_at
     or signature_record.signed_at > signature_record.authenticated_at + interval '5 minutes'
     or signature_record.signed_at < clock_timestamp() - interval '5 minutes'
     or signature_record.signed_at > clock_timestamp() + interval '30 seconds'
     or new.ocorrido_em < signature_record.signed_at - interval '30 seconds'
     or new.ocorrido_em > clock_timestamp() + interval '30 seconds' then
    raise exception 'Janela temporal da assinatura e do evento invalida';
  end if;

  if signature_record.request_id is distinct from new.request_id then
    raise exception 'Assinatura e evento devem pertencer a mesma requisicao';
  end if;

  if exists (
    select 1
    from public.resultado_workflow_evento used_event
    where used_event.assinatura_eletronica_id = new.assinatura_eletronica_id
  ) then
    raise exception 'Assinatura eletronica ja utilizada por outro evento';
  end if;

  if coalesce(new.metadata ->> 'versao', '') !~ '^[1-9][0-9]*$'
     or (new.metadata ->> 'versao')::integer <> current_version then
    raise exception 'Metadata do evento nao corresponde a versao assinada';
  end if;

  return new;
end;
$$;

create or replace function public.ensure_signed_result_transition_event()
