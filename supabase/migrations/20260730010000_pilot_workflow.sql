-- Repara vínculos e duplicidades que eram aceitos pelo esquema anterior antes
-- de criar as novas restrições. Nenhuma linha histórica é removida fisicamente.
insert into public.amostra_parametro (amostra_id, parametro_id)
select distinct ra.amostra_id, ra.parametro_id
from public.resultado_analise ra
on conflict (amostra_id, parametro_id) do nothing;

with ranked as (
  select ra.id,
         row_number() over (
           partition by ra.amostra_id, ra.parametro_id
           order by coalesce(ra.datadapublicacao, ra.created_at) desc, ra.id desc
         ) as position
  from public.resultado_analise ra
  where ra.deleted_at is null
), archived as (
  update public.resultado_analise ra
  set deleted_at = timezone('utc', now()),
      deletion_reason = coalesce(
        ra.deletion_reason,
        'Duplicidade legada arquivada na implantação do workflow piloto.'
      )
  from ranked r
  where ra.id = r.id and r.position > 1
  returning ra.*
)
