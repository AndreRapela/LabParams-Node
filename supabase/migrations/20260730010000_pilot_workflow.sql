-- Reconcilia amostras legadas com seus resultados e registra cada mudança na
-- cadeia de custódia, sem reabrir amostras que já possuíam estado terminal.
with desired as (
  select a.id,
         a.status_amostra as previous_status,
         case
           when count(ra.id) filter (where ra.deleted_at is null) = 0
             then a.status_amostra
           when bool_and(ra.status_resultado = 'publicado')
                filter (where ra.deleted_at is null)
             then 'concluida'
           else 'em_analise'
         end as next_status,
         a.local_atual
  from public.amostra a
  left join public.resultado_analise ra on ra.amostra_id = a.id
  where a.deleted_at is null
  group by a.id
), changed as (
  update public.amostra a
  set status_amostra = d.next_status,
      status_atualizado_em = timezone('utc', now()),
      status_atualizado_por = null
  from desired d
  where a.id = d.id
    and d.previous_status in ('recebida','em_triagem','em_analise','aguardando_revisao')
    and d.previous_status <> d.next_status
  returning a.id, d.previous_status, d.next_status, d.local_atual
)
