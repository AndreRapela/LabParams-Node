-- Mantem compatibilidade com uma eventual execucao anterior desta migracao:
-- explicita a versao nos eventos e o contexto das assinaturas ja consumidas.
update public.resultado_workflow_evento event
set resultado_versao = coalesce(
  case
    when event.metadata ->> 'versao' ~ '^[1-9][0-9]*$'
      then (event.metadata ->> 'versao')::integer
    else null
  end,
  result.versao
)
from public.resultado_analise result
where result.id = event.resultado_id
  and event.resultado_versao is null;

update public.assinatura_eletronica signature
set entity_version = coalesce(signature.entity_version, event.resultado_versao),
    status_origem = coalesce(signature.status_origem, event.status_anterior),
    status_destino = coalesce(signature.status_destino, event.status_novo)
from public.resultado_workflow_evento event
where event.assinatura_eletronica_id = signature.id
  and signature.entity_type = 'resultado_analise'
  and signature.action in ('APPROVE', 'REJECT', 'PUBLISH', 'REOPEN')
  and (
    signature.entity_version is null
    or signature.status_origem is null
    or signature.status_destino is null
  );

with latest_signature as (
  select distinct on (event.resultado_id)
         event.resultado_id, event.assinatura_eletronica_id
  from public.resultado_workflow_evento event
  where event.assinatura_eletronica_id is not null
  order by event.resultado_id, event.ocorrido_em desc, event.id desc
)
update public.resultado_analise result
set ultima_assinatura_eletronica_id = latest.assinatura_eletronica_id
from latest_signature latest
where result.id = latest.resultado_id
  and result.ultima_assinatura_eletronica_id is null;

