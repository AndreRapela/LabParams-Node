      and (signature.metadata ->> 'entity_version')::integer = new.versao
      and signature.authenticated_at <= signature.signed_at
      and signature.signed_at <= signature.authenticated_at + interval '5 minutes'
      and signature.signed_at >= clock_timestamp() - interval '5 minutes'
      and signature.signed_at <= clock_timestamp() + interval '30 seconds'
      and signature.signed_at >= new.emitido_em - interval '30 seconds'
      and signature.signed_at <= new.emitido_em + interval '30 seconds'
  ) then
    raise exception 'Assinatura eletrônica de emissão inválida';
  end if;
  return new;
end;
$$;

create or replace function public.protect_amostra_parametro_scope()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  target_sample_id integer;
begin
  target_sample_id := case when tg_op = 'INSERT' then new.amostra_id else old.amostra_id end;
  if exists (
    select 1 from public.resultado_analise where amostra_id = target_sample_id
  ) or (
    tg_op = 'UPDATE'
    and new.amostra_id is distinct from old.amostra_id
    and exists (
      select 1 from public.resultado_analise where amostra_id = new.amostra_id
    )
  ) then
    raise exception 'Escopo de parâmetros congelado após o primeiro resultado';
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

