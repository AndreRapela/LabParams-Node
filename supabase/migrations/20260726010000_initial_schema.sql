drop trigger if exists set_matriz_updated_at on public.matriz;
create trigger set_matriz_updated_at
before update on public.matriz
for each row execute function public.set_updated_at();

drop trigger if exists set_legislacao_updated_at on public.legislacao;
create trigger set_legislacao_updated_at
before update on public.legislacao
for each row execute function public.set_updated_at();

drop trigger if exists set_parametro_updated_at on public.parametro;
create trigger set_parametro_updated_at
before update on public.parametro
for each row execute function public.set_updated_at();

drop trigger if exists set_amostra_updated_at on public.amostra;
create trigger set_amostra_updated_at
before update on public.amostra
for each row execute function public.set_updated_at();

drop trigger if exists set_resultado_updated_at on public.resultado_analise;
create trigger set_resultado_updated_at
before update on public.resultado_analise
for each row execute function public.set_updated_at();

create or replace function public.sync_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  perfil_administrativo text;
begin
  perfil_administrativo := case
    when new.raw_app_meta_data ->> 'perfil' in ('Gestor', 'Analista', 'Usuário')
      then new.raw_app_meta_data ->> 'perfil'
    else null
  end;

  insert into public.usuario (id, nome, email, telefone, perfil)
  values (
    new.id,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'nome'), ''),
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      split_part(new.email, '@', 1)
    ),
    new.email,
    nullif(trim(new.raw_user_meta_data ->> 'telefone'), ''),
    coalesce(perfil_administrativo, 'Usuário')
  )
  on conflict (id) do update
  set nome = excluded.nome,
      email = excluded.email,
      telefone = excluded.telefone,
      perfil = coalesce(perfil_administrativo, usuario.perfil);

  return new;
end;
$$;

drop trigger if exists sync_auth_user_profile on auth.users;
create trigger sync_auth_user_profile
after insert or update of email, raw_user_meta_data, raw_app_meta_data
on auth.users
for each row execute function public.sync_auth_user();

insert into public.usuario (id, nome, email, telefone, perfil)
select
  id,
  coalesce(
    nullif(trim(raw_user_meta_data ->> 'nome'), ''),
    nullif(trim(raw_user_meta_data ->> 'full_name'), ''),
    split_part(email, '@', 1)
  ),
  email,
  nullif(trim(raw_user_meta_data ->> 'telefone'), ''),
  case
    when raw_app_meta_data ->> 'perfil' in ('Gestor', 'Analista', 'Usuário')
      then raw_app_meta_data ->> 'perfil'
    else 'Usuário'
  end
from auth.users
where email is not null
on conflict (id) do nothing;

alter table public.usuario enable row level security;
alter table public.matriz enable row level security;
alter table public.legislacao enable row level security;
alter table public.parametro enable row level security;
alter table public.amostra enable row level security;
alter table public.amostra_parametro enable row level security;
alter table public.resultado_analise enable row level security;

revoke all on table public.usuario from anon, authenticated;
revoke all on table public.matriz from anon, authenticated;
revoke all on table public.legislacao from anon, authenticated;
revoke all on table public.parametro from anon, authenticated;
revoke all on table public.amostra from anon, authenticated;
revoke all on table public.amostra_parametro from anon, authenticated;
revoke all on table public.resultado_analise from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
revoke execute on function public.set_updated_at() from public, anon, authenticated;
revoke execute on function public.sync_auth_user() from public, anon, authenticated;

commit;
