begin;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create table if not exists public.usuario (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  email text not null,
  telefone text,
  perfil text not null default 'Usuário'
    check (perfil in ('Gestor', 'Analista', 'Usuário')),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists usuario_email_lower_uidx
  on public.usuario (lower(email));

create table if not exists public.matriz (
  id integer generated by default as identity primary key,
  nome text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists matriz_nome_lower_uidx
  on public.matriz (lower(nome));

create table if not exists public.legislacao (
  id integer generated by default as identity primary key,
  nome text not null,
  sigla text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists legislacao_sigla_lower_uidx
  on public.legislacao (lower(sigla));

create table if not exists public.parametro (
  id integer generated by default as identity primary key,
  nome text not null,
  unidade_medida text not null default '',
  valor_parametro numeric(18, 6),
  limite_minimo numeric(18, 6),
  limite_maximo numeric(18, 6),
  matriz_id integer not null references public.matriz(id) on update cascade on delete restrict,
  legislacao_id integer not null references public.legislacao(id) on update cascade on delete restrict,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint parametro_limites_validos check (
    limite_minimo is null
    or limite_maximo is null
    or limite_minimo <= limite_maximo
  )
);

create unique index if not exists parametro_contexto_uidx
  on public.parametro (lower(nome), matriz_id, legislacao_id);
create index if not exists parametro_matriz_idx on public.parametro (matriz_id);
create index if not exists parametro_legislacao_idx on public.parametro (legislacao_id);

create table if not exists public.amostra (
  id integer generated by default as identity primary key,
  codigo_amostra text not null unique,
  numero_da_amostra text not null unique,
  data_coleta timestamptz not null,
  localizacao text,
  matriz_id integer not null references public.matriz(id) on update cascade on delete restrict,
  usuario_id uuid not null references public.usuario(id) on update cascade on delete restrict,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists amostra_matriz_idx on public.amostra (matriz_id);
create index if not exists amostra_usuario_idx on public.amostra (usuario_id);
create index if not exists amostra_data_coleta_idx on public.amostra (data_coleta desc);

create table if not exists public.amostra_parametro (
  amostra_id integer not null references public.amostra(id) on update cascade on delete cascade,
  parametro_id integer not null references public.parametro(id) on update cascade on delete restrict,
  created_at timestamptz not null default timezone('utc', now()),
  primary key (amostra_id, parametro_id)
);

create index if not exists amostra_parametro_parametro_idx
  on public.amostra_parametro (parametro_id);

create table if not exists public.resultado_analise (
  id integer generated by default as identity primary key,
  valor_medido numeric(18, 6) not null check (valor_medido >= 0),
  amostra_id integer not null references public.amostra(id) on update cascade on delete cascade,
  parametro_id integer not null references public.parametro(id) on update cascade on delete restrict,
  datacoleta timestamptz not null,
  datadapublicacao timestamptz not null default timezone('utc', now()),
  codigodaamostra text not null,
  numerodaamostra text not null,
  matriz text not null,
  legislacao text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists resultado_amostra_idx
  on public.resultado_analise (amostra_id);
create index if not exists resultado_parametro_idx
  on public.resultado_analise (parametro_id);
create index if not exists resultado_datacoleta_idx
  on public.resultado_analise (datacoleta desc);
create index if not exists resultado_publicacao_idx
  on public.resultado_analise (datadapublicacao desc);
create index if not exists resultado_created_at_idx
  on public.resultado_analise (created_at desc);
create index if not exists resultado_parametro_data_idx
  on public.resultado_analise (parametro_id, datacoleta desc);

drop trigger if exists set_usuario_updated_at on public.usuario;
